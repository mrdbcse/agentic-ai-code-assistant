    system_id BIGINT REFERENCES system(id),
    module_activation_id BIGINT,
    code TEXT,
    manufacturer_name TEXT,
    quantity INTEGER,
    PRIMARY KEY (system_id, module_activation_id)
);

-- SYSTEM_INVERTERS
CREATE TABLE system_inverter (
    system_id BIGINT REFERENCES system(id),
    inverter_activation_id BIGINT,
    code TEXT,
    manufacturer_name TEXT,
    quantity INTEGER,
    PRIMARY KEY (system_id, inverter_activation_id)
);

-- SYSTEM_BATTERIES
CREATE TABLE system_battery (
    system_id BIGINT REFERENCES system(id),
    battery_activation_id BIGINT,
    code TEXT,
    manufacturer_name TEXT,
    quantity INTEGER,
    PRIMARY KEY (system_id, battery_activation_id)
);

-- SYSTEM_OTHERS
CREATE TABLE system_other (
    system_id BIGINT REFERENCES system(id),
    other_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code TEXT,
    manufacturer_name TEXT,
    quantity INTEGER
