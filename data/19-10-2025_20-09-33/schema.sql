-- MODULES TABLE (for system modules)
CREATE TABLE system_module (
    id SERIAL PRIMARY KEY,
    system_id BIGINT REFERENCES system(id),
    module_activation_id BIGINT,
    code VARCHAR(100),
    manufacturer_name VARCHAR(100),
    quantity INTEGER
);

-- INVERTERS TABLE (for system inverters)
CREATE TABLE system_inverter (
    id SERIAL PRIMARY KEY,
    system_id BIGINT REFERENCES system(id),
    inverter_activation_id BIGINT,
    code VARCHAR(100),
    manufacturer_name VARCHAR(100),
    quantity INTEGER
);

-- BATTERIES TABLE (for system batteries)
CREATE TABLE system_battery (
    id SERIAL PRIMARY KEY,
    system_id BIGINT REFERENCES system(id),
    battery_activation_id BIGINT,
    code VARCHAR(100),
    manufacturer_name VARCHAR(100),
    quantity INTEGER
);

-- EVENTS TABLE
CREATE TABLE event (
    id BIGINT PRIMARY KEY,
    org TEXT,
    project_id BIGINT REFERENCES project(id),
    duration INTEGER,
    event_type_id INTEGER,
    action_id BIGINT,
    start TIMESTAMP,
    "end" TIMESTAMP,
    created_date TIMESTAMP,
    modified_date TIMESTAMP,
    who_display VARCHAR(200),
    who_email VARCHAR(200),
    who_portrait_image_public_url TEXT,
    notify_team_members JSONB,
