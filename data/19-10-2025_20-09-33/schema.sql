    task_status INTEGER,
    is_complete BOOLEAN,
    notes TEXT,
    is_archived BOOLEAN,
    categories INTEGER[],
    form_config INTEGER,
    team_members JSONB,
    event_icon INTEGER
);

-- ACTIONS TABLE
CREATE TABLE action (
    id BIGINT PRIMARY KEY,
    url TEXT,
    org TEXT,
    stage INTEGER,
    title TEXT,
    "order" INTEGER,
    created_date TIMESTAMP,
    modified_date TIMESTAMP,
    share_with_orgs JSONB,
    org_shared_time JSONB,
    workflows JSONB
);

-- ACTION_EVENTS TABLE (linking actions to events)
CREATE TABLE action_event (
    action_id BIGINT REFERENCES action(id),
    event_id BIGINT REFERENCES event(id),
    PRIMARY KEY (action_id, event_id)
);

-- AVAILABLE CUSTOMER ACTIONS
CREATE TABLE available_customer_action (
    id SERIAL PRIMARY KEY,
    project_id BIGINT REFERENCES project(id),
    system_uuid UUID,
    actions_available JSONB
);

