-- PostgreSQL schema for Solar Energy Project JSON
-- This schema is normalized and covers all nested key-value pairs

-- ORGANIZATION TABLE
CREATE TABLE organization (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255),
    url TEXT
);

